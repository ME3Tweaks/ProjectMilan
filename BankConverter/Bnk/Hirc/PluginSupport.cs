namespace BankConverter.Bnk.Hirc;

/// <summary>
/// Decodes Wwise's packed AkPluginID, and tells apart plugins Audiokinetic ships (which any Wwise runtime has)
/// from ones a studio registered itself (which only that studio's build has).
///
/// The packing is AKMAKECLASSID, verified in Ghidra against <c>AK::SoundEngine::RegisterPlugin</c> in BOTH
/// shipping binaries - LE3 (<c>MassEffect3.exe-11.3.2</c> @ 7ff74b53fee0) and ME3 (<c>MassEffect3_cr.exe</c>
/// @ 00e6c210) compute the registry key identically:
/// <code>
/// key = (pluginID * 0x1000 + companyID) * 0x10 + (pluginType &amp; 0xF)
/// </code>
/// so the company is the MIDDLE field, not the top one. Sanity check: 0x00040001 = company 0 (Audiokinetic),
/// plugin 4 (Vorbis), type 1 (Codec).
/// </summary>
public static class PluginSupport
{
    // AkTypes.h: the company-ID range studios register their own Source/Effect plugins under.
    private const uint CompanyIdPluginDevMin = 64;
    private const uint CompanyIdPluginDevMax = 255;

    /// <summary>Plugin type: 1 Codec, 2 Source, 3 Effect, ... (low 4 bits).</summary>
    public static uint GetPluginType(uint pluginId) => pluginId & 0xF;

    /// <summary>Registering company. 0 is Audiokinetic; 64..255 is the studio/plugin-developer range.</summary>
    public static uint GetCompanyId(uint pluginId) => (pluginId >> 4) & 0xFFF;

    /// <summary>The plugin's own ID within its company.</summary>
    public static uint GetPluginNumber(uint pluginId) => pluginId >> 16;

    /// <summary>
    /// True only for a plugin registered under a studio's own company ID, which LE3's stock Wwise runtime would
    /// have no factory for.
    ///
    /// This used to read the top 16 bits (the plugin number) and test THAT against the company range, which made
    /// essentially every stock Audiokinetic effect look third-party - their plugin numbers land in 64..255 - so
    /// they were being stripped out of converted banks. Measured against the shipping games: every Fx object and
    /// every source plugin in ME3 and LE3 alike is company 0, i.e. there is no third-party plugin content here at
    /// all. ME3 registers 21 plugins, 19 of them company 0 plus two at company 256 (0x00671003, 0x006E1003), and
    /// LE3 ships and uses both of those in its own always-loaded banks.
    /// </summary>
    public static bool IsThirdParty(uint pluginId)
    {
        var companyId = GetCompanyId(pluginId);
        return companyId is >= CompanyIdPluginDevMin and <= CompanyIdPluginDevMax;
    }

    /// <summary>
    /// True for a Source plugin (type 2) - audio generated by a plugin rather than read from a media file.
    /// Distinct from <see cref="IsThirdParty"/>: stock LE3 banks give EVERY source plugin, Audiokinetic or not,
    /// an InMemoryMediaSize of 0 and an empty parameter block (148/148 in the resident set, 435/435 in LMP base),
    /// so that treatment keys off the type, not off who wrote the plugin.
    /// </summary>
    public static bool IsSourcePlugin(uint pluginId) => GetPluginType(pluginId) == 2;
}
